bool bochs_vbe_present(void)
{
    outw(0x01CE, 0x00);
    uint16_t id = inw(0x01CF);
    return (id & 0xFFF0) == 0xB0C0;
}

static uint32_t detect_bochs_vbe_lfb(void)
{
    if (!bochs_vbe_present())
    {
        c_puts("[VBE] Bochs VBE not detected - will use VGA fallback\n");
        return 0;
    }
    for (int bus = 0; bus < 256; bus++)
    {
        for (int dev = 0; dev < 32; dev++)
        {
            uint32_t vendor_dev = pci_config_read(bus, dev, 0, 0x00);
            if ((vendor_dev & 0xFFFF) == 0xFFFF)
                continue;
            uint32_t class_rev = pci_config_read(bus, dev, 0, 0x08);
            if (((class_rev >> 24) & 0xFF) != 0x03)
                continue;
            uint32_t bar0 = pci_config_read(bus, dev, 0, 0x10);
            uint32_t bar1 = pci_config_read(bus, dev, 0, 0x14);
            if ((bar0 & 0x01) == 0 && bar0 != 0)
                return bar0 & 0xFFFFFFF0;
            if ((bar1 & 0x01) == 0 && bar1 != 0)
                return bar1 & 0xFFFFFFF0;
        }
    }
    c_puts("[VBE] Bochs VBE present but no PCI BAR found, using default 0xFD000000\n");
    return 0xFD000000;
}

uint32_t *gpu_setup_framebuffer(void)
{
    font_build_8x8();

    uint16_t info_width = vbe_info->width;
    uint16_t info_height = vbe_info->height;
    uint8_t info_bpp = vbe_info->bpp;
    uint32_t info_fb = vbe_info->framebuffer;

    c_puts("[VBE] setup_fb: vbe_info w="); 
    { char buf[6]; int n = 0; uint16_t v = info_width; if(v>=1000){buf[n++]='0'+v/1000;v%=1000;} if(v>=100){buf[n++]='0'+v/100;v%=100;} if(v>=10){buf[n++]='0'+v/10;} v%=10; buf[n++]='0'+v; buf[n]=0; c_puts(buf); }
    c_puts(" h=");
    { char buf[6]; int n = 0; uint16_t v = info_height; if(v>=1000){buf[n++]='0'+v/1000;v%=1000;} if(v>=100){buf[n++]='0'+v/100;v%=100;} if(v>=10){buf[n++]='0'+v/10;} v%=10; buf[n++]='0'+v; buf[n]=0; c_puts(buf); }
    c_puts(" bpp=");
    { char buf[4]; buf[0]='0'+info_bpp/100; buf[1]='0'+(info_bpp/10)%10; buf[2]='0'+info_bpp%10; buf[3]=0; c_puts(buf); }
    c_puts(" fb=");
    { char buf[11]; int i; uint32_t v = info_fb; buf[0]='0'; buf[1]='x'; for(i=9;i>=2;i--){uint32_t d=v&0xFu; buf[i]=(char)(d<10?'0'+d:'a'+d-10); v>>=4;} buf[10]=0; c_puts(buf); }
    c_putc('\n');

    /* On real VMware Workstation the bootloader's VBE block can carry a
     * stale framebuffer address once vmware_svga_set_mode() reprogrammed
     * the device.  FB_START on the device itself is always current, so it
     * wins whenever the SVGA driver is alive.
    */
    if (vmware_svga_available())
    {
        extern uint32_t vmware_svga_get_fb_addr(void);
        uint32_t svga_fb = vmware_svga_get_fb_addr();
        if (svga_fb != 0)
        {
            if (svga_fb != info_fb)
                c_puts("[VBE] Using live SVGA FB_START over boot info\n");
            info_fb = svga_fb;
        }
    }

    bool have_vesa = (info_width >= 640 && info_width <= 4096 &&
                      info_height >= 480 && info_height <= 4096 &&
                      (info_bpp == 16 || info_bpp == 24 || info_bpp == 32));

    /* If the SVGA driver just programmed a real mode but the boot-info
     * dimensions look broken, trust the values vmware_svga_set_mode()
     * wrote back into the info block rather than dropping to VGA.
     * The VGA fallback below calls set_mode_13h(), which needs BIOS
     * int 10h and cannot work from protected mode -> guaranteed black
     * screen.  Never reach it while a working LFB exists.
    */
    if (!have_vesa && vmware_svga_available())
    {
        c_puts("[VBE] Boot info unusable; trusting SVGA mode\n");
        have_vesa = (info_width > 0 && info_height > 0 && info_bpp >= 24);
    }

    if (have_vesa && info_fb == 0)
    {
        info_fb = detect_bochs_vbe_lfb();
        if (info_fb != 0)
            vbe_info->framebuffer = info_fb;
        else if (bochs_vbe_present())
            info_fb = 0xFD000000;
    }
    else if (have_vesa && info_fb == 0xFD000000)
    {
        uint32_t detected = detect_bochs_vbe_lfb();
        if (detected != 0)
            info_fb = detected;
    }

    if (have_vesa && info_fb != 0)
    {
        vbe_active = true;
        vga_fallback = false;
        framebuffer = (uint32_t *)info_fb;
        screen_width = info_width;
        screen_height = info_height;
        screen_bpp = info_bpp;

        c_puts("[VBE] VESA path: vbe_active=1 fb="); 
        { char buf[11]; int i; uint32_t v = (uint32_t)(uintptr_t)framebuffer; buf[0]='0'; buf[1]='x'; for(i=9;i>=2;i--){uint32_t d=v&0xFu; buf[i]=(char)(d<10?'0'+d:'a'+d-10); v>>=4;} buf[10]=0; c_puts(buf); }
        c_putc('\n');

        uint32_t min_pitch = (uint32_t)screen_width * ((uint32_t)screen_bpp / 8);
        screen_pitch = 0;

        if (vmware_svga_available())
        {
            c_puts("[VBE] pitch: trying vmware_svga_get_pitch\n");
            uint32_t vm_pitch = vmware_svga_get_pitch();
            c_puts("[VBE] vm_pitch=");
            { char buf[11]; int i; uint32_t v = vm_pitch; buf[0]='0'; buf[1]='x'; for(i=9;i>=2;i--){uint32_t d=v&0xFu; buf[i]=(char)(d<10?'0'+d:'a'+d-10); v>>=4;} buf[10]=0; c_puts(buf); }
            c_putc('\n');
            if (vm_pitch >= min_pitch)
                screen_pitch = (int)vm_pitch;
        }
        if (screen_pitch == 0 && vmware_svga_available() &&
            vbe_info->lin_pitch != 0 && (uint32_t)vbe_info->lin_pitch >= min_pitch)
            screen_pitch = vbe_info->lin_pitch;
        if (screen_pitch == 0 && vmware_svga_available() &&
            vbe_info->pitch != 0 && (uint32_t)vbe_info->pitch >= min_pitch)
            screen_pitch = vbe_info->pitch;
        if (screen_pitch == 0 && bochs_vbe_present())
        {
            outw(0x01CE, 0x06);
            uint16_t virt_w = inw(0x01CF);
            if (virt_w >= (uint16_t)screen_width)
                screen_pitch = (int)virt_w * (screen_bpp / 8);
        }
        if (screen_pitch == 0 || (uint32_t)screen_pitch < min_pitch)
            screen_pitch = (int)min_pitch;

        if (double_buffered && backbuffer && backbuffer != framebuffer)
            kfree(backbuffer);

        uint32_t bb_size = (uint32_t)screen_width * (uint32_t)screen_height * 4;
        backbuffer = (uint32_t *)kmalloc(bb_size);

        if (backbuffer)
        {
            double_buffered = true;
            bb_stride_px = screen_width;
            c_puts("[VBE] Double buffering active\n");
            uint32_t bb_total = (uint32_t)screen_width * (uint32_t)screen_height;
            for (uint32_t i = 0; i < bb_total; i++)
                backbuffer[i] = 0;
        }
        else
        {
            backbuffer = framebuffer;
            double_buffered = false;
            bb_stride_px = screen_pitch / (screen_bpp / 8);
            c_puts("[VBE] Warning: direct rendering (no heap)\n");
        }

        uint8_t *fb_ptr = (uint8_t *)framebuffer;
        for (int y = 0; y < screen_height; y++)
        {
            uint8_t *row = fb_ptr + (uint32_t)y * (uint32_t)screen_pitch;
            for (uint32_t x = 0; x < min_pitch; x++)
                row[x] = 0;
        }
        return backbuffer;
    }

    c_puts("[VGA] Falling back to Mode 13h\n");
    vbe_active = false;
    vga_fallback = true;
    screen_width = 320;
    screen_height = 200;
    screen_bpp = 8;
    screen_pitch = 320;
    bb_stride_px = 320;
    framebuffer = (uint32_t *)0xA0000;
    backbuffer = framebuffer;
    double_buffered = false;
    set_mode_13h();
    setup_palette();
    return framebuffer;
}

