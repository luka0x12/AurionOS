/*
 * VBE graphics driver for AurionOS.
 *
 * TEXT CONTRACT:
 *   gpu_draw_char / gpu_draw_string = 8x16 cell, 8px advance, 16px line.
 *   gpu_draw_char_scaled / _string_scaled = same master, scale x scale blocks.
 *   gpu_draw_char_big / _string_big = scale 2.
 *
 * One master: 8x16 with VGA-classic metrics (caps rows 2-11, baseline 12,
 * x-height rows 6-12, descenders to 15, 2px stems). Boot screen, installer
 * and VGA text mode all consume this table; font_8x8 is derived from it so
 * any legacy 8x8 consumer shows the same family.
 */
