bool gpu_set_mode(uint16_t width, uint16_t height, uint8_t bpp)
{
    bool ok = vmware_svga_available()
        ? vmware_svga_set_mode(width, height, bpp)
        : vesa_set_mode(width, height, bpp);
    if (!ok)
        return false;

    vbe_info->width = width;
    vbe_info->height = height;
    vbe_info->bpp = bpp;

    extern void io_wait(void);
    for (int i = 0; i < 100; i++)
        io_wait();

    if (!gpu_setup_framebuffer())
        return false;
    gpu_clear(0xFF000000);
    return true;
}

static uint8_t rgb_to_vga(uint32_t color)
{
    uint8_t r = (color >> 16) & 0xFF;
    uint8_t g = (color >> 8) & 0xFF;
    uint8_t b = color & 0xFF;
    int brightness = (r + g + b) / 3;
    if (brightness < 32)
        return 0;
    if (r > g && r > b)
        return (brightness > 128) ? 12 : 4;
    if (g > r && g > b)
        return (brightness > 128) ? 10 : 2;
    if (b > r && b > g)
        return (brightness > 128) ? 9 : 1;
    if (brightness > 200)
        return 15;
    if (brightness > 128)
        return 7;
    return 8;
}

void gpu_clear(uint32_t color)
{
    if (vga_fallback)
    {
        uint8_t vga_col = rgb_to_vga(color);
        uint8_t *vga = (uint8_t *)0xA0000;
        for (int i = 0; i < 320 * 200; i++)
            vga[i] = vga_col;
        return;
    }
    for (int y = 0; y < screen_height; y++)
    {
        uint32_t *row = backbuffer + (uint32_t)y * (uint32_t)bb_stride_px;
        for (int x = 0; x < screen_width; x++)
            row[x] = color;
    }
}

void gpu_draw_pixel(int x, int y, uint32_t color)
{
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height)
        return;
    if (vga_fallback)
    {
        ((uint8_t *)0xA0000)[y * 320 + x] = rgb_to_vga(color);
        return;
    }
    backbuffer[(uint32_t)y * (uint32_t)bb_stride_px + x] = color;
}

void gpu_fill_rect(int x, int y, int w, int h, uint32_t color)
{
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > screen_width) w = screen_width - x;
    if (y + h > screen_height) h = screen_height - y;
    if (w <= 0 || h <= 0) return;

    if (vga_fallback)
    {
        uint8_t vga_col = rgb_to_vga(color);
        uint8_t *vga = (uint8_t *)0xA0000;
        for (int dy = 0; dy < h; dy++)
        {
            int off = (y + dy) * 320 + x;
            for (int dx = 0; dx < w; dx++)
                vga[off + dx] = vga_col;
        }
        return;
    }
    for (int dy = 0; dy < h; dy++)
    {
        uint32_t *row = backbuffer + (uint32_t)(y + dy) * (uint32_t)bb_stride_px + x;
        for (int dx = 0; dx < w; dx++)
            row[dx] = color;
    }
}

void gpu_fill_rect_blend(int x, int y, int w, int h,
                         uint32_t color, uint8_t alpha)
{
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (w <= 0 || h <= 0) return;
    if (x >= screen_width || y >= screen_height) return;
    if (x + w > screen_width) w = screen_width - x;
    if (y + h > screen_height) h = screen_height - y;

    if (alpha == 255) { gpu_fill_rect(x, y, w, h, color); return; }
    if (alpha == 0) return;
    if (vga_fallback) { gpu_fill_rect(x, y, w, h, color); return; }

    uint32_t r_src = (color >> 16) & 0xFF;
    uint32_t g_src = (color >> 8) & 0xFF;
    uint32_t b_src = color & 0xFF;
    uint32_t inv = 255 - alpha;

    for (int j = 0; j < h; j++)
    {
        uint32_t *row = backbuffer + (uint32_t)(y + j) * (uint32_t)bb_stride_px + x;
        for (int i = 0; i < w; i++)
        {
            uint32_t d = row[i];
            uint32_t r = (r_src * alpha + ((d >> 16) & 0xFF) * inv + 128) >> 8;
            uint32_t g = (g_src * alpha + ((d >> 8) & 0xFF) * inv + 128) >> 8;
            uint32_t b = (b_src * alpha + (d & 0xFF) * inv + 128) >> 8;
            row[i] = 0xFF000000 | (r << 16) | (g << 8) | b;
        }
    }
}

void gpu_blur_rect(int x, int y, int w, int h)
{
    if (vga_fallback || !backbuffer || !double_buffered)
        return;
    if (x < 1) { w += (x - 1); x = 1; }
    if (y < 1) { h += (y - 1); y = 1; }
    if (x + w >= screen_width - 1) w = screen_width - 1 - x;
    if (y + h >= screen_height - 1) h = screen_height - 1 - y;
    if (w <= 0 || h <= 0) return;

    uint32_t *base = (uint32_t *)kmalloc((uint32_t)w * 4 * 3);
    if (!base)
        return;
    uint32_t *top = base;
    uint32_t *mid = base + w;
    uint32_t *bot = base + w * 2;

    for (int i = 0; i < w; i++)
    {
        top[i] = backbuffer[(uint32_t)(y - 1) * (uint32_t)bb_stride_px + x + i];
        mid[i] = backbuffer[(uint32_t)y * (uint32_t)bb_stride_px + x + i];
    }

    for (int j = 0; j < h; j++)
    {
        int cy = y + j;
        uint32_t *dst = backbuffer + (uint32_t)cy * (uint32_t)bb_stride_px + x;
        if (cy + 1 < screen_height)
        {
            for (int i = 0; i < w; i++)
                bot[i] = backbuffer[(uint32_t)(cy + 1) * (uint32_t)bb_stride_px + x + i];
        }
        for (int i = 0; i < w; i++)
        {
            uint32_t r = 0, g = 0, b = 0;
            for (int dx = -1; dx <= 1; dx++)
            {
                int ci = i + dx;
                if (ci < 0) ci = 0;
                if (ci >= w) ci = w - 1;
                uint32_t p0 = top[ci], p1 = mid[ci], p2 = bot[ci];
                r += ((p0 >> 16) & 0xFF) + ((p1 >> 16) & 0xFF) + ((p2 >> 16) & 0xFF);
                g += ((p0 >> 8) & 0xFF) + ((p1 >> 8) & 0xFF) + ((p2 >> 8) & 0xFF);
                b += (p0 & 0xFF) + (p1 & 0xFF) + (p2 & 0xFF);
            }
            dst[i] = 0xFF000000 | ((r / 9) << 16) | ((g / 9) << 8) | (b / 9);
        }
        uint32_t *tmp = top;
        top = mid;
        mid = bot;
        bot = tmp;
    }
    kfree(base);
}

void gpu_draw_char(int x, int y, uint8_t c, uint32_t fg, uint32_t bg)
{
    if (c > 127)
        c = '?';
    const uint8_t *glyph = font_8x16[c];
    for (int row = 0; row < 16; row++)
    {
        uint8_t bits = glyph[row];
        if (bits == 0)
        {
            if (bg != 0)
                for (int col = 0; col < 8; col++)
                    gpu_draw_pixel(x + col, y + row, bg);
            continue;
        }
        for (int col = 0; col < 8; col++)
        {
            uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
            if (bg == 0 && color == 0)
                continue;
            gpu_draw_pixel(x + col, y + row, color);
        }
    }
}

void gpu_draw_string(int x, int y, const uint8_t *str, uint32_t fg, uint32_t bg)
{
    int cx = x;
    while (*str)
    {
        if (*str == '\n')
        {
            cx = x;
            y += 16;
        }
        else
        {
            gpu_draw_char(cx, y, *str, fg, bg);
            cx += 8;
        }
        str++;
    }
}

void gpu_draw_char_scaled(int x, int y, uint8_t c, uint32_t fg, uint32_t bg, int scale)
{
    if (scale < 1)
        scale = 1;
    if (c > 127)
        c = '?';
    const uint8_t *glyph = font_8x16[c];
    for (int row = 0; row < 16; row++)
    {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++)
        {
            uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
            if (bg == 0 && color == 0)
                continue;
            gpu_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}

void gpu_draw_string_scaled(int x, int y, const uint8_t *str, uint32_t fg, uint32_t bg, int scale)
{
    if (scale < 1)
        scale = 1;
    int cx = x;
    while (*str)
    {
        if (*str == '\n')
        {
            cx = x;
            y += 16 * scale;
        }
        else
        {
            gpu_draw_char_scaled(cx, y, *str, fg, bg, scale);
            cx += 8 * scale;
        }
        str++;
    }
}

void gpu_draw_char_big(int x, int y, uint8_t c, uint32_t fg, uint32_t bg)
{
    gpu_draw_char_scaled(x, y, c, fg, bg, 2);
}

void gpu_draw_string_big(int x, int y, const uint8_t *str, uint32_t fg, uint32_t bg)
{
    gpu_draw_string_scaled(x, y, str, fg, bg, 2);
}

int gpu_flush(void)
{
    if (!vbe_active)
        return 0;

    if (double_buffered && backbuffer != framebuffer)
    {
        if (screen_bpp == 32)
        {
            for (int y = 0; y < screen_height; y++)
            {
                uint32_t *src = backbuffer + (uint32_t)y * (uint32_t)bb_stride_px;
                uint32_t *dst = (uint32_t *)((uint8_t *)framebuffer +
                                             (uint32_t)y * (uint32_t)screen_pitch);
                for (int x = 0; x < screen_width; x++)
                    dst[x] = src[x];
                if ((y & 31) == 0)
                    sched_heartbeat();
            }
        }
        else if (screen_bpp == 24)
        {
            uint8_t *dst_base = (uint8_t *)framebuffer;
            for (int y = 0; y < screen_height; y++)
            {
                uint32_t *src = backbuffer + (uint32_t)y * (uint32_t)bb_stride_px;
                uint8_t *dst = dst_base + (uint32_t)y * (uint32_t)screen_pitch;
                for (int x = 0; x < screen_width; x++)
                {
                    uint32_t c = src[x];
                    *dst++ = (uint8_t)(c & 0xFF);
                    *dst++ = (uint8_t)((c >> 8) & 0xFF);
                    *dst++ = (uint8_t)((c >> 16) & 0xFF);
                }
                if ((y & 31) == 0)
                    sched_heartbeat();
            }
        }
        else if (screen_bpp == 16)
        {
            uint16_t *dst_base = (uint16_t *)framebuffer;
            uint32_t pitch_px = (uint32_t)screen_pitch / 2;
            for (int y = 0; y < screen_height; y++)
            {
                uint32_t *src = backbuffer + (uint32_t)y * (uint32_t)bb_stride_px;
                uint16_t *dst = dst_base + (uint32_t)y * pitch_px;
                for (int x = 0; x < screen_width; x++)
                {
                    uint32_t c = src[x];
                    dst[x] = (uint16_t)((((c >> 16) & 0xFF) >> 3) << 11 |
                                        (((c >> 8) & 0xFF) >> 2) << 5 |
                                        ((c & 0xFF) >> 3));
                }
                if ((y & 31) == 0)
                    sched_heartbeat();
            }
        }
    }

    /* VMware SVGA requires a FIFO UPDATE command to refresh the host
     * display.  Without it, writes to the LFB are invisible to the user
     * even though they are in memory.  Must run in ALL paths:
     * double-buffered (copy + update) AND direct-rendering (update only).
    */
   
    if (vmware_svga_available())
        vmware_svga_update(0, 0, screen_width, screen_height);
    return 0;
}

