/* set_text_mode (weak): VGA text mode 3, verbatim from vbe_graphics.c */
__attribute__((weak))
void set_text_mode(void)
{
    extern void vmware_svga_disable(void);
    vmware_svga_disable();

    /* Disable Bochs VBE if present */
    ex_outb(0x01CE, 4);
    ex_outb(0x01CF, 0);

    /* Misc output: 80x25 timing */
    ex_outb(0x3C2, 0x67);

    /* Sequencer */
    ex_outb(0x3C4, 0x00); ex_outb(0x3C5, 0x01);
    ex_outb(0x3C4, 0x01); ex_outb(0x3C5, 0x00);
    ex_outb(0x3C4, 0x02); ex_outb(0x3C5, 0x03);
    ex_outb(0x3C4, 0x03); ex_outb(0x3C5, 0x00);
    ex_outb(0x3C4, 0x04); ex_outb(0x3C5, 0x02);
    ex_outb(0x3C4, 0x00); ex_outb(0x3C5, 0x03);

    /* Unlock CRTC */
    ex_outb(0x3D4, 0x11);
    ex_outb(0x3D5, ex_inb(0x3D5) & 0x7F);

    static const uint8_t crtc[25] = {
        0x5F,0x4F,0x50,0x82,0x55,0x81,0xBF,0x1F,
        0x00,0x4F,0x0D,0x0E,0x00,0x00,0x00,0x00,
        0x9C,0x8E,0x8F,0x28,0x1F,0x96,0xB9,0xA3,0xFF
    };
    for (int i = 0; i < 25; i++) {
        ex_outb(0x3D4, (uint8_t)i);
        ex_outb(0x3D5, crtc[i]);
    }

    /* Graphics controller */
    ex_outb(0x3CE, 0x00); ex_outb(0x3CF, 0x00);
    ex_outb(0x3CE, 0x01); ex_outb(0x3CF, 0x00);
    ex_outb(0x3CE, 0x02); ex_outb(0x3CF, 0x00);
    ex_outb(0x3CE, 0x03); ex_outb(0x3CF, 0x00);
    ex_outb(0x3CE, 0x04); ex_outb(0x3CF, 0x00);
    ex_outb(0x3CE, 0x05); ex_outb(0x3CF, 0x10);
    ex_outb(0x3CE, 0x06); ex_outb(0x3CF, 0x0E);
    ex_outb(0x3CE, 0x07); ex_outb(0x3CF, 0x00);
    ex_outb(0x3CE, 0x08); ex_outb(0x3CF, 0xFF);

    /* Attribute controller */
    ex_inb(0x3DA);
    static const uint8_t pal[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x14,0x07,
        0x38,0x39,0x3A,0x3B,0x3C,0x3D,0x3E,0x3F
    };
    for (int i = 0; i < 16; i++) {
        ex_inb(0x3DA);
        ex_outb(0x3C0, (uint8_t)i);
        ex_outb(0x3C0, pal[i]);
    }
    ex_inb(0x3DA); ex_outb(0x3C0, 0x10); ex_outb(0x3C0, 0x0C);
    ex_inb(0x3DA); ex_outb(0x3C0, 0x11); ex_outb(0x3C0, 0x00);
    ex_inb(0x3DA); ex_outb(0x3C0, 0x12); ex_outb(0x3C0, 0x0F);
    ex_inb(0x3DA); ex_outb(0x3C0, 0x13); ex_outb(0x3C0, 0x08);
    ex_inb(0x3DA); ex_outb(0x3C0, 0x14); ex_outb(0x3C0, 0x00);
    ex_inb(0x3DA); ex_outb(0x3C0, 0x20);

    /* Clear text video memory */
    volatile uint16_t *vga_text = (volatile uint16_t *)0xB8000;
    for (int i = 0; i < 80 * 25; i++) {
        vga_text[i] = 0x0720;
    }
}