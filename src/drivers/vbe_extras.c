/* vbe_extras.c - weak fallbacks for font_8x8 and set_text_mode.
 *
 * Normally vbe_graphics.c exports these as strong globals. They are weak
 * here so that:
 *   - if vbe_graphics.c provides them (strong), the linker uses those and
 *     silently ignores this file (no multiple-definition error);
 *   - if vbe_graphics.c has them as `static` (invisible outside its own
 *     translation unit) or is missing them, these weak definitions satisfy
 *     the external references from boot_screen.o (font_8x8) and desktop.o
 *     (set_text_mode), fixing the undefined-reference link errors.
 * Bodies are copied verbatim from the canonical vbe_graphics.c so behaviour
 * is identical whenever these fallbacks end up being the linked copy.
*/

#include <stdint.h>
#include <stdbool.h>

/* port I/O helpers (file-local; vbe_graphics.c keeps its own) */
static inline void ex_outb(uint16_t port, uint8_t val)
{
    __asm__ volatile("outb %0, %1" : : "a"(val), "Nd"(port));
}
static inline uint8_t ex_inb(uint16_t port)
{
    uint8_t ret;
    __asm__ volatile("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

