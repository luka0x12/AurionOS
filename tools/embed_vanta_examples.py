#!/usr/bin/env python3
"""Embed the shipped Vanta programs in the kernel's starter-file catalog."""

import argparse
import json
from pathlib import Path

def main():
    project = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--examples", type=Path, default=project / "src/coding/examples")
    parser.add_argument("--output", type=Path, default=project / "src/coding/vanta_examples.c")
    args = parser.parse_args()
    files = sorted(args.examples.glob("*.vanta"))
    if not files:
        parser.error(f"No Vanta examples in {args.examples}")

    lines = [
        "/* Generated by tools/embed_vanta_examples.py. Edit the .vanta sources. */",
        '#include "vanta_examples.h"',
        '#include "fs.h"',
        "extern FSEntry fs_table[FS_MAX_FILES];",
        "extern int fs_count;",
        "extern int str_cmp(const char *, const char *);",
        "extern int save_file_content(const char *, const char *, int);",
        "",
    ]
    for index, path in enumerate(files):
        source = path.read_text(encoding="utf-8")
        if not source.isascii() or not 0 < len(source) <= 8192:
            parser.error(f"{path}: examples must be ASCII and fit the 8192-byte file limit")
        if len("/Development/" + path.name) >= 56 or not path.name.isascii():
            parser.error(f"{path}: name exceeds the filesystem limit")
        lines.append(f"static const char example_{index}[] =")
        lines.extend("    " + json.dumps(line) for line in source.splitlines(keepends=True))
        lines.extend([";", ""])
    lines.append("const VantaExample vanta_examples[] = {")
    for index, path in enumerate(files):
        name = json.dumps("/Development/" + path.name)
        lines.append(f"    {{{name}, example_{index}, sizeof(example_{index}) - 1}},")
    lines.extend([
        "};",
        "const uint32_t vanta_example_count = sizeof(vanta_examples) / sizeof(vanta_examples[0]);",
        """
int vanta_seed_examples(void)
{
    for (uint32_t i = 0; i < vanta_example_count; i++) {
        int exists = 0;
        for (int j = 0; j < fs_count; j++) {
            if (str_cmp(fs_table[j].name, vanta_examples[i].path) == 0) {
                exists = 1;
                break;
            }
        }
        if (!exists && save_file_content(vanta_examples[i].path,
                                        vanta_examples[i].source,
                                        (int)vanta_examples[i].size) != 0)
            return -1;
    }
    return 0;
}
""",
    ])
    args.output.write_bytes("\n".join(lines).encode("ascii"))
    print(f"Embedded {len(files)} Vanta examples")


if __name__ == "__main__":
    main()
